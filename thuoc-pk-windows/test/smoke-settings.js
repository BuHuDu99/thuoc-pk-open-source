const { app, BrowserWindow, ipcMain } = require('electron')
const assert = require('assert/strict'), fs = require('fs'), path = require('path'), os = require('os')
const { DEFAULT_CONFIG, validateConfig } = require('../src/das-contract')
app.setPath('userData', fs.mkdtempSync(path.join(os.tmpdir(), 'cis-settings-')))
app.disableHardwareAcceleration()
let config = validateConfig(DEFAULT_CONFIG), saves = 0
let state = { status: 'windows-only' }
ipcMain.handle('das-config', () => ({ config, state, diagnostic: { status: state.status, detected: {} }, platform: 'darwin' }))
ipcMain.handle('das-save', (_event, value) => { config = validateConfig(value); saves += 1; return { ok: true } })
const wait = (ms) => new Promise((resolve) => setTimeout(resolve, ms))
fs.mkdirSync(path.join(__dirname, '../docs'), { recursive: true })
app.whenReady().then(async () => {
  const timer = setTimeout(() => app.exit(1), 15000)
  const window = new BrowserWindow({ width: 620, height: 560, show: false, webPreferences: { preload: path.join(__dirname, '../src/preload.js'), sandbox: true, contextIsolation: true, nodeIntegration: false } })
  await window.loadFile(path.join(__dirname, '../src/das-settings.html')); await wait(300)
  assert.equal(await window.webContents.executeJavaScript(`document.querySelector('details').open`), false)
  assert.equal(await window.webContents.executeJavaScript(`document.querySelector('#platform-note').hidden`), false)
  await window.webContents.executeJavaScript(`document.querySelector('#demo').click()`)
  assert.equal(await window.webContents.executeJavaScript(`document.querySelector('#reading-weight').textContent`), '12,5')
  assert.equal(await window.webContents.executeJavaScript(`document.querySelector('#reading-height').textContent`), '82')
  assert.equal(await window.webContents.executeJavaScript(`document.querySelector('#reading-label').textContent`), 'DỮ LIỆU MINH HỌA')
  assert.equal(saves, 0)
  await wait(150)
  const image = await window.webContents.capturePage()
  fs.writeFileSync(path.join(__dirname, '../docs/cis-connection-preview.png'), image.resize({ width: 620 }).toPNG())
  await window.webContents.executeJavaScript(`document.querySelector('#unit').value = 'months'; document.querySelector('#form').requestSubmit()`)
  await wait(150)
  assert.equal(saves, 1); assert.equal(config.ageUnit, 'months')
  assert.deepEqual(config.height, DEFAULT_CONFIG.height)
  assert.equal(await window.webContents.executeJavaScript(`document.querySelector('#reading-weight').textContent`), '—')
  assert.equal(await window.webContents.executeJavaScript(`document.querySelector('#reading-height').textContent`), '—')
  const overflow = await window.webContents.executeJavaScript(`document.documentElement.scrollWidth > innerWidth`)
  assert.equal(overflow, false)
  state = { status: 'reader-failed', reason: 'reader-timeout' }
  await wait(850)
  assert.equal(await window.webContents.executeJavaScript(`document.querySelector('#status-title').textContent`), 'Chưa kết nối được CIS')
  assert.match(await window.webContents.executeJavaScript(`document.querySelector('#status-description').textContent`), /CIS không trả lời/)
  state = { status: 'reader-failed', reason: 'runtime-unavailable' }
  await wait(850)
  assert.match(await window.webContents.executeJavaScript(`document.querySelector('#status-description').textContent`), /\.NET Framework 3\.5/)
  console.log('PASS: settings/demo/save, optional height, no overflow and actionable timeout/dependency messages.')
  clearTimeout(timer); app.exit(0)
}).catch((error) => { console.error(error); app.exit(1) })
